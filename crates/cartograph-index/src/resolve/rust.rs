    #[test]
    fn paths_in_code() {
        let repo = Repo::new(&[
            (
                "Cargo.toml",
                "[workspace]\nmembers = [\"crates/*\"]\n[workspace.package]\nedition = \"2021\"\n",
            ),
            (
                "crates/lib-a/Cargo.toml",
                "[package]\nname = \"lib-a\"\nedition.workspace = true\n",
            ),
            ("crates/lib-a/src/lib.rs", "pub mod m;\npub fn run() {}\n"),
            ("crates/lib-a/src/m.rs", "pub struct T;\n"),
            (
                "crates/app/Cargo.toml",
                "[package]\nname = \"app\"\nedition.workspace = true\n[dependencies]\n\
                 lib-a = { path = \"../lib-a\" }\nserde_json = \"1\"\n",
            ),
            (
                "crates/app/src/main.rs",
                "mod cmd;\nuse lib_a::m::T;\n\
                 fn main() {\n    lib_a::run();\n    let _t: lib_a::m::T = lib_a::m::T;\n    \
                 let n = u32::MAX;\n    let v = serde_json::json!(null);\n    \
                 std::process::exit(cmd::go(n));\n    lib_a::run();\n}\n\
                 mod tests { fn t() { super::main(); crate::cmd::go(1); } }\n",
            ),
            (
                "crates/app/src/cmd.rs",
                "pub fn go(n: u32) -> i32 { super::helper(); unknown::x(); lib_a::m::T; 0 }\n",
            ),
        ]);
        let v = repo.resolve();
        let t = |f, s| find(&v, f, s).to_string();
        let main = "crates/app/src/main.rs";
        assert_eq!(t(main, "lib_a::run"), "file:crates/lib-a/src/lib.rs ~");
        assert_eq!(t(main, "lib_a::m::T"), "file:crates/lib-a/src/m.rs ~");
        assert_eq!(t(main, "serde_json::json"), "external:crates:serde_json ~");
        assert_eq!(t(main, "std::process::exit"), "external:rust:std");
        assert_eq!(t(main, "cmd::go"), "file:crates/app/src/cmd.rs ~");
        assert_eq!(t(main, "crate::cmd::go"), "file:crates/app/src/cmd.rs ~");
        assert_eq!(
            t("crates/app/src/cmd.rs", "super::helper"),
            "file:crates/app/src/main.rs ~"
        );
        // Paths that lead nowhere or back to the file itself are dropped, not unresolved.
        for (f, s) in [
            (main, "u32::MAX"),
            (main, "super::main"),
            ("crates/app/src/cmd.rs", "unknown::x"),
        ] {
            assert!(
                !v.iter().any(|(vf, vs, _)| vf == f && vs == s),
                "{f} {s}: {v:#?}"
            );
        }

        // One site per target: a target a `use` or `mod` already reaches gets none, and
        // a path reaching a new one is kept once, at its first line.
        let sites: Vec<(String, String, String)> = repo
            .sites()
            .into_iter()
            .filter(|(at, _, _)| at.starts_with(main))
            .collect();
        let shown: Vec<String> = sites
            .iter()
            .map(|(at, s, t)| format!("{at} {s} -> {t}"))
            .collect();
        assert_eq!(
            shown,
            vec![
                "crates/app/src/main.rs:1 mod cmd -> file:crates/app/src/cmd.rs",
                "crates/app/src/main.rs:2 lib_a::m::T -> file:crates/lib-a/src/m.rs",
                "crates/app/src/main.rs:4 lib_a::run -> file:crates/lib-a/src/lib.rs",
                "crates/app/src/main.rs:7 serde_json::json -> external:crates:serde_json",
                "crates/app/src/main.rs:8 std::process::exit -> external:rust:std",
            ]
        );
    }

    /// `pub use m_i::*` in the parent and `use super::*` in every child form glob cycles;
    /// a missing module must be reported without exploring them exponentially.
    #[test]
    fn glob_reexport_cycles_stay_cheap() {
        let mut lib = String::new();
        let mut files: Vec<(String, String)> = vec![(
            "Cargo.toml".into(),
            "[package]\nname = \"x\"\nedition = \"2021\"\n".into(),
        )];
        for i in 0..20 {
            lib.push_str(&format!("mod m_{i};\npub use m_{i}::*;\n"));
            files.push((format!("src/m_{i}.rs"), "use super::*;\n".into()));
        }
        lib.push_str("use crate::generated::Foo;\n");
        files.push(("src/lib.rs".into(), lib));
        let repo = Repo { files };
        CALLS.with(|c| c.set(0));
        let v = repo.resolve();
        let calls = CALLS.with(std::cell::Cell::get);
        let got = find(&v, "src/lib.rs", "crate::generated::Foo");
        assert!(got.contains("generated by a macro"), "{got}");
        assert!(calls < 5_000, "{calls} path resolutions");
    }
