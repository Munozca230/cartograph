/// Whether `top` (a top-level module name) is in the Python standard library.
pub fn is_python_stdlib(top: &str) -> bool {
    PYTHON_STDLIB.binary_search(&top).is_ok()
}

/// Whether `top` (a top-level module name, no `node:` prefix) is a Node.js built-in.
pub fn is_node_builtin(top: &str) -> bool {
    NODE_BUILTINS.binary_search(&top).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_are_sorted_and_known_names_match() {
        assert!(PYTHON_STDLIB.is_sorted());
        assert!(NODE_BUILTINS.is_sorted());
        for m in [
            "os",
            "__future__",
            "typing",
            "distutils",
            "tomllib",
            "_thread",
        ] {
            assert!(is_python_stdlib(m), "{m}");
        }
        assert!(!is_python_stdlib("numpy"));
        for m in ["fs", "path", "child_process", "worker_threads"] {
            assert!(is_node_builtin(m), "{m}");
        }
        assert!(!is_node_builtin("react"));
        assert!(!is_node_builtin("test"), "node:test is prefix-only");
    }
}
